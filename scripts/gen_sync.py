#!/usr/bin/env python
"""Generate fcctl/_sync from fcctl/_async with unasync. `--check` exits 1 if committed _sync differs.

_io.py is NOT generated: scripts/_io_sync.py is copied verbatim (the one handwritten override).
"""
from __future__ import annotations

import argparse
import filecmp
import shutil
import sys
import tempfile
from pathlib import Path

import unasync

ROOT = Path(__file__).resolve().parent.parent
REPLACE = {"AsyncClient": "Client", "aiter_lines": "iter_lines", "aclose": "close", "_async": "_sync",
           "AsyncIterator": "Iterator"}
OVERRIDES = {"_io.py": ROOT / "scripts" / "_io_sync.py"}
HEADER = "# GENERATED by scripts/gen_sync.py from fcctl/_async. DO NOT EDIT.\n"


def generate(dest: Path, src: Path = ROOT / "fcctl" / "_async") -> None:
    work = Path(tempfile.mkdtemp())
    try:
        rule = unasync.Rule(str(src), str(work), additional_replacements=REPLACE)
        files = sorted(p for p in src.rglob("*.py") if p.relative_to(src).as_posix() not in OVERRIDES)
        unasync.unasync_files([str(p) for p in files], [rule])
        dest.mkdir(parents=True, exist_ok=True)
        for p in sorted(work.rglob("*.py")):
            out = dest / p.relative_to(work)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(HEADER + p.read_text())
        for name, o in OVERRIDES.items():
            (dest / name).write_text(HEADER + o.read_text())
    finally:
        shutil.rmtree(work, ignore_errors=True)


def same(a: Path, b: Path) -> bool:
    na, nb = (sorted(p.relative_to(d).as_posix() for p in d.rglob("*.py")) for d in (a, b))
    return na == nb and all(filecmp.cmp(a / n, b / n, shallow=False) for n in na)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    target = ROOT / "fcctl" / "_sync"
    if a.check:
        tmp = Path(tempfile.mkdtemp())
        generate(tmp / "_sync")
        ok = target.is_dir() and same(tmp / "_sync", target)
        shutil.rmtree(tmp, ignore_errors=True)
        print("ok" if ok else "fcctl/_sync is stale: run scripts/gen_sync.py", file=sys.stderr if not ok else sys.stdout)
        return 0 if ok else 1
    for old in target.rglob("*.py") if target.is_dir() else []:
        old.unlink()
    generate(target)
    return 0


if __name__ == "__main__":
    sys.exit(main())
