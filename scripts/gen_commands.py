#!/usr/bin/env python
"""Generate docs/COMMANDS.md from the argparse tree. `--check` exits 1 if the committed file differs."""
from __future__ import annotations

import argparse
import difflib
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "COMMANDS.md"
sys.path.insert(0, str(ROOT))
os.environ["COLUMNS"] = "100"

HEADER = ("<!-- GENERATED by scripts/gen_commands.py. DO NOT EDIT. "
          "Regenerate with `python scripts/gen_commands.py`. -->\n")


def _clean(s) -> str:
    s = re.sub(r"\s+", " ", str(s).replace("%%", "%")).strip()
    home = str(Path.home())
    s = s.replace(home, "~").replace(str(ROOT), ".")
    return s.replace("|", "\\|")


def _cell(v) -> str:
    return f"`{_clean(v)}`" if v not in (None, "") else ""


def _walk(parser, path):
    """Yield (path, parser, help) in parser order."""
    yield path, parser
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            helps = {ca.dest: ca.help for ca in a._choices_actions}
            for n, sp in a.choices.items():
                sp._gen_help = helps.get(n) or ""
                yield from _walk(sp, path + [n])


def _rows(parser):
    rows = []
    for a in parser._actions:
        if isinstance(a, (argparse._SubParsersAction, argparse._HelpAction)):
            continue
        if a.help == argparse.SUPPRESS:
            continue
        flag = ", ".join(a.option_strings) if a.option_strings else a.dest
        mv = a.metavar if isinstance(a.metavar, str) else (
            "" if not a.option_strings and a.metavar is None else
            (a.metavar and " ".join(a.metavar)) or (a.dest.upper() if a.option_strings and a.nargs != 0 else ""))
        choices = ", ".join(str(c) for c in a.choices) if a.choices else ""
        d = a.default
        default = "" if d in (None, argparse.SUPPRESS, False) else d
        rows.append(f"| {_cell(flag)} | {_cell(mv)} | {_cell(choices)} | {_cell(default)} | {_clean(a.help or '')} |")
    return rows


def _examples(parser) -> list[str]:
    ep = parser.epilog or ""
    lines = [ln.rstrip() for ln in ep.strip("\n").splitlines()]
    out = []
    for ln in lines:
        if ln.strip().lower().startswith("examples"):
            continue
        out.append(ln.strip())
    return [ln for ln in out if ln]


def render() -> str:
    from fcctl.cli.main import build_parser
    parser = build_parser()
    parser.prog = "fcctl"
    nodes = []
    for path, p in _walk(parser, []):
        nodes.append((path, p))
    out = [HEADER, "# fcctl command reference\n"]
    out.append("## Contents\n")
    out.append("- [Global flags](#global-flags)")
    for path, _ in nodes[1:]:
        title = "fcctl " + " ".join(path)
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        out.append(f"- [`{title}`](#{anchor})")
    out.append("\n## Global flags\n")
    out.append(f"Usage: `{_clean(parser.format_usage().replace('usage: ', '', 1))}`\n")
    g = _rows(parser)
    out += ["| Flag | Metavar | Choices | Default | Help |", "| --- | --- | --- | --- | --- |"] + g
    out.append("")
    ex = _examples(parser)
    if ex:
        out += ["Examples:\n", "```"] + ex + ["```\n"]
    for path, p in nodes[1:]:
        p.prog = "fcctl " + " ".join(path)
        out.append(f"## fcctl {' '.join(path)}\n")
        h = _clean(getattr(p, "_gen_help", "") or p.description or "")
        if h:
            out.append(h + "\n")
        out.append(f"Usage: `{_clean(p.format_usage().replace('usage: ', '', 1))}`\n")
        rows = _rows(p)
        if rows:
            out += ["| Flag | Metavar | Choices | Default | Help |", "| --- | --- | --- | --- | --- |"] + rows + [""]
        ex = _examples(p)
        if ex:
            out += ["Examples:\n", "```"] + ex + ["```\n"]
    return "\n".join(out).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        cur = OUT.read_text() if OUT.exists() else ""
        if cur == text:
            print("ok")
            return 0
        diff = "".join(list(difflib.unified_diff(cur.splitlines(True), text.splitlines(True),
                                                 "docs/COMMANDS.md", "generated"))[:20])
        print(diff, file=sys.stderr)
        print("docs/COMMANDS.md is stale: run python scripts/gen_commands.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
