"""Static shell completion scripts (bash, zsh, fish) generated from the argparse tree.

The scripts are plain text derived from ``build_parser()``: no runtime dependency, and nothing
is read from the network, config or session state while completing.
"""
from __future__ import annotations

import argparse
import re

SHELLS = ("bash", "zsh", "fish")
_FILE_DESTS = {"file", "dest", "data", "out"}
_FILE_METAVARS = {"FILE", "PATH", "DIR"}


def _is_file(a: argparse.Action) -> bool:
    if a.choices:
        return False
    mv = a.metavar if isinstance(a.metavar, str) else ""
    return a.dest in _FILE_DESTS or mv.upper() in _FILE_METAVARS


def _help(a) -> str:
    h = getattr(a, "help", None)
    if not h or h == argparse.SUPPRESS:
        return ""
    return re.sub(r"\s+", " ", h.replace("%%", "%")).strip()


def _takes_arg(a: argparse.Action) -> bool:
    n = a.nargs
    return n is None or n in ("*", "+") or (isinstance(n, int) and n > 0)


def _walk(parser: argparse.ArgumentParser, name: str, help: str) -> dict:
    node = {"name": name, "help": help, "subs": [], "opts": [], "pos": []}
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            helps = {id(ca): None for ca in a._choices_actions}
            by_name = {ca.dest: _help(ca) for ca in a._choices_actions}
            parser_help: dict[int, str] = {}
            for n, sp in a.choices.items():
                if n in by_name:
                    parser_help[id(sp)] = by_name[n]
            del helps
            for n, sp in a.choices.items():
                node["subs"].append(_walk(sp, n, parser_help.get(id(sp), "")))
        elif a.option_strings:
            node["opts"].append({
                "strings": list(a.option_strings), "help": _help(a), "arg": _takes_arg(a),
                "optional": a.nargs == "?", "choices": [str(c) for c in a.choices or []],
                "file": _is_file(a), "metavar": a.metavar if isinstance(a.metavar, str) else a.dest,
            })
        else:
            node["pos"].append({
                "dest": a.dest, "nargs": a.nargs, "choices": [str(c) for c in a.choices or []],
                "file": _is_file(a), "help": _help(a),
            })
    return node


def build_tree(parser: argparse.ArgumentParser | None = None) -> dict:
    """Return {'root': node, 'globals': [opt, ...]}; global options are the root's options."""
    if parser is None:
        from .main import build_parser
        parser = build_parser()
    root = _walk(parser, "fcctl", "")
    gl = root["opts"]
    gstrings = {s for o in gl for s in o["strings"]}

    def strip(n):
        n["opts"] = [o for o in n["opts"] if not (set(o["strings"]) & gstrings)]
        for s in n["subs"]:
            strip(s)
    root["opts"] = []
    strip(root)
    return {"root": root, "globals": gl}


def paths(tree: dict) -> list[list[str]]:
    out: list[list[str]] = []

    def rec(n, p):
        for s in n["subs"]:
            out.append(p + [s["name"]])
            rec(s, p + [s["name"]])
    rec(tree["root"], [])
    return out


def nodes(tree: dict):
    """Yield (path list, node) for the root and every command."""
    def rec(n, p):
        yield p, n
        for s in n["subs"]:
            yield from rec(s, p + [s["name"]])
    yield from rec(tree["root"], [])


def long_flags(tree: dict) -> list[str]:
    seen = []
    for o in tree["globals"]:
        seen += [s for s in o["strings"] if s.startswith("--")]
    for _, n in nodes(tree):
        for o in n["opts"]:
            seen += [s for s in o["strings"] if s.startswith("--")]
    return sorted(set(seen))


def _q(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


def _pstr(p: list[str]) -> str:
    return " ".join(p)


# ---------------------------------------------------------------- bash

def gen_bash(tree: dict) -> str:
    L: list[str] = []
    a = L.append
    gopts = " ".join(s for o in tree["globals"] for s in o["strings"])
    a("# bash completion for fcctl (generated by `fcctl completion bash`; do not edit)")
    a(f"_fcctl_globalopts={_q(gopts)}")

    def fn(name, rows, default=""):
        a(f"{name}() {{ case \"$1\" in")
        for pat, val in rows:
            a(f"  {pat}) {val};;")
        if default:
            a(f"  *) {default};;")
        a("esac; }")

    rows = []
    for p, n in nodes(tree):
        if n["subs"]:
            rows.append((f'"{_pstr(p)}"', "echo " + _q(" ".join(s["name"] for s in n["subs"]))))
    fn("_fcctl_subs", rows)
    rows = []
    for p, n in nodes(tree):
        if n["opts"]:
            rows.append((f'"{_pstr(p)}"', "echo " + _q(" ".join(s for o in n["opts"] for s in o["strings"]))))
    fn("_fcctl_opts", rows)
    rows = []
    for p, n in nodes(tree):
        ch = [c for pp in n["pos"] for c in pp["choices"]]
        if ch:
            rows.append((f'"{_pstr(p)}"', "echo " + _q(" ".join(ch))))
    fn("_fcctl_poschoices", rows)
    rows = []
    for p, n in nodes(tree):
        if any(pp["file"] for pp in n["pos"]):
            rows.append((f'"{_pstr(p)}"', "return 0"))
    fn("_fcctl_posfile", rows, "return 1")

    def optrows(pred, val):
        r = []
        for o in tree["globals"]:
            if pred(o):
                r.append(("|".join(f'*"|{s}"' for s in o["strings"]), val(o)))
        for p, n in nodes(tree):
            for o in n["opts"]:
                if pred(o):
                    r.append(("|".join(f'"{_pstr(p)}|{s}"' for s in o["strings"]), val(o)))
        return r
    fn("_fcctl_takes_arg", optrows(lambda o: o["arg"], lambda o: "return 0"), "return 1")
    # the call passes "$1|$2"-style keys through a wrapper so the patterns above match
    fn("_fcctl_choices", optrows(lambda o: bool(o["choices"]), lambda o: "echo " + _q(" ".join(o["choices"]))))
    fn("_fcctl_isfile", optrows(lambda o: o["file"], lambda o: "return 0"), "return 1")
    a(r'''
_fcctl_values() {
  local ch
  ch="$(_fcctl_choices "$1|$2")"
  if [ -n "$ch" ]; then
    COMPREPLY=( $(compgen -P "$4" -W "$ch" -- "$3") )
  elif _fcctl_isfile "$1|$2"; then
    compopt -o filenames 2>/dev/null
    local IFS=$'\n'
    if [[ "$3" == @* ]]; then
      COMPREPLY=( $(compgen -P "$4@" -f -- "${3#@}") )
    else
      COMPREPLY=( $(compgen -P "$4" -f -- "$3") )
    fi
  fi
}

_fcctl() {
  local cur="${COMP_WORDS[COMP_CWORD]}" prev="" path="" w i skip=0 subs
  COMPREPLY=()
  [ "$COMP_CWORD" -gt 0 ] && prev="${COMP_WORDS[COMP_CWORD-1]}"
  for ((i = 1; i < COMP_CWORD; i++)); do
    w="${COMP_WORDS[i]}"
    if [ "$skip" = 1 ]; then skip=0; continue; fi
    case "$w" in
      --*=*) continue ;;
      -*) if _fcctl_takes_arg "$path|$w"; then skip=1; fi; continue ;;
    esac
    if [[ " $(_fcctl_subs "$path") " == *" $w "* ]]; then path="${path:+$path }$w"; fi
  done
  if [ "$cur" = "=" ] && [ "$COMP_CWORD" -ge 2 ]; then
    _fcctl_values "$path" "$prev" "" ""; return 0
  fi
  if [ "$prev" = "=" ] && [ "$COMP_CWORD" -ge 3 ]; then
    _fcctl_values "$path" "${COMP_WORDS[COMP_CWORD-2]}" "$cur" ""; return 0
  fi
  if [[ "$cur" == --*=* ]]; then
    _fcctl_values "$path" "${cur%%=*}" "${cur#*=}" "${cur%%=*}="; return 0
  fi
  if [ "$skip" = 1 ]; then
    _fcctl_values "$path" "$prev" "$cur" ""; return 0
  fi
  if [[ "$cur" == -* ]]; then
    COMPREPLY=( $(compgen -W "$(_fcctl_opts "$path") $_fcctl_globalopts" -- "$cur") )
    return 0
  fi
  subs="$(_fcctl_subs "$path") $(_fcctl_poschoices "$path")"
  COMPREPLY=( $(compgen -W "$subs" -- "$cur") )
  if [ "${#COMPREPLY[@]}" -eq 0 ] && _fcctl_posfile "$path"; then
    compopt -o filenames 2>/dev/null
    local IFS=$'\n'
    COMPREPLY=( $(compgen -f -- "$cur") )
  fi
  return 0
}
complete -F _fcctl fcctl''')
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- zsh

def _zq(s: str) -> str:
    """Escape for use inside a single-quoted zsh _arguments spec description."""
    s = s.replace("[", "\\[").replace("]", "\\]")
    return s.replace("'", "'\\''")


def _zaction(choices, file) -> str:
    if choices:
        return "(" + " ".join(choices) + ")"
    return "_files" if file else " "


def _zopt_specs(o: dict) -> list[str]:
    out = []
    desc = _zq(o["help"])
    for s in o["strings"]:
        spec = f"{s}[{desc}]"
        if o["arg"]:
            spec += f":{_zq(o['metavar'] or 'value').replace(':', ' ')}:{_zaction(o['choices'], o['file'])}"
        elif o["optional"]:
            spec += f"::{_zq(o['metavar'] or 'value').replace(':', ' ')}:{_zaction(o['choices'], o['file'])}"
        out.append("'" + spec + "'")
    return out


def _zfn(p: list[str]) -> str:
    return "_fcctl" + "".join("_" + re.sub(r"\W", "_", x) for x in p)


def gen_zsh(tree: dict) -> str:
    L: list[str] = ["#compdef fcctl", "# zsh completion for fcctl (generated by `fcctl completion zsh`; do not edit)", ""]
    a = L.append
    gspecs = [sp for o in tree["globals"] for sp in _zopt_specs(o)]
    a("_fcctl_globals=(")
    for sp in gspecs:
        a("  " + sp)
    a(")")
    a("")
    for p, n in nodes(tree):
        a(f"{_zfn(p)}() {{")
        a("  local curcontext=\"$curcontext\" state line")
        a("  typeset -A opt_args")
        args = ['"${_fcctl_globals[@]}"'] + [sp for o in n["opts"] for sp in _zopt_specs(o)]
        if n["subs"]:
            a("  local -a cmds")
            a("  cmds=(")
            for s in n["subs"]:
                a(f"    {_q(s['name'].replace(':', chr(92) + ':') + ':' + s['help'])}")
            a("  )")
            args += ["'1: :->cmds'", "'*::arg:->args'"]
        else:
            idx = 0
            for pp in n["pos"]:
                label = _zq(pp["dest"]).replace(":", " ")
                act = _zaction(pp["choices"], pp["file"])
                if pp["nargs"] in ("*", "+"):
                    args.append(f"'*:{label}:{act}'")
                elif pp["nargs"] == "?":
                    idx += 1
                    args.append(f"'{idx}::{label}:{act}'")
                else:
                    idx += 1
                    args.append(f"'{idx}:{label}:{act}'")
        a("  _arguments -C \\")
        a(" \\\n".join("    " + x for x in args))
        if n["subs"]:
            a("  case $state in")
            a("    cmds) _describe -t commands 'command' cmds ;;")
            a("    args)")
            a("      case $words[1] in")
            for s in n["subs"]:
                a(f"        {s['name']}) {_zfn(p + [s['name']])} ;;")
            a("      esac ;;")
            a("  esac")
        a("}")
        a("")
    a('_fcctl "$@"')
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- fish

def _fq(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _fopt(cond: str, o: dict) -> str:
    parts = ["complete -c fcctl"]
    if cond:
        parts.append(f"-n {_fq(cond)}")
    for s in o["strings"]:
        parts.append(f"-l {s[2:]}" if s.startswith("--") else f"-s {s[1:]}")
    if o["arg"]:
        if o["choices"]:
            parts += ["-x", f"-a {_fq(' '.join(o['choices']))}"]
        elif o["file"]:
            parts += ["-r", "-F"]
        else:
            parts += ["-x"]
    if o["help"]:
        parts.append(f"-d {_fq(o['help'])}")
    return " ".join(parts)


def gen_fish(tree: dict) -> str:
    L: list[str] = ["# fish completion for fcctl (generated by `fcctl completion fish`; do not edit)", "complete -c fcctl -f", ""]
    a = L.append
    argflags = set()
    for o in tree["globals"]:
        if o["arg"]:
            argflags.update(o["strings"])
    for _, n in nodes(tree):
        for o in n["opts"]:
            if o["arg"]:
                argflags.update(o["strings"])
    a(f"set -g __fcctl_argflags {' '.join(sorted(argflags))}")
    a("function __fcctl_subs")
    a("    switch \"$argv[1]\"")
    for p, n in nodes(tree):
        if n["subs"]:
            a(f"        case {_fq(_pstr(p))}")
            a(f"            echo {' '.join(s['name'] for s in n['subs'])}")
    a("    end")
    a("end")
    a("function __fcctl_path")
    a("    set -l path ''")
    a("    set -l skip 0")
    a("    set -l toks (commandline -opc)")
    a("    set -e toks[1]")
    a("    for t in $toks")
    a("        if test $skip = 1")
    a("            set skip 0")
    a("            continue")
    a("        end")
    a("        if string match -q -- '-*' $t")
    a("            if contains -- $t $__fcctl_argflags")
    a("                set skip 1")
    a("            end")
    a("            continue")
    a("        end")
    a("        if contains -- $t (__fcctl_subs \"$path\")")
    a("            set path (string trim \"$path $t\")")
    a("        end")
    a("    end")
    a("    echo $path")
    a("end")
    a("function __fcctl_at")
    a("    set -l p (__fcctl_path)")
    a("    test \"$p\" = \"$argv[1]\"")
    a("end")
    a("")
    for o in tree["globals"]:
        a(_fopt("", o))
    for p, n in nodes(tree):
        cond = f'__fcctl_at "{_pstr(p)}"'
        for s in n["subs"]:
            d = f" -d {_fq(s['help'])}" if s["help"] else ""
            a(f"complete -c fcctl -n {_fq(cond)} -a {s['name']}{d}")
        for o in n["opts"]:
            a(_fopt(cond, o))
        for pp in n["pos"]:
            if pp["choices"]:
                a(f"complete -c fcctl -n {_fq(cond)} -a {_fq(' '.join(pp['choices']))}")
            elif pp["file"]:
                a(f"complete -c fcctl -n {_fq(cond)} -F")
    return "\n".join(L) + "\n"


def generate(shell: str, parser: argparse.ArgumentParser | None = None) -> str:
    tree = build_tree(parser)
    if shell == "bash":
        return gen_bash(tree)
    if shell == "zsh":
        return gen_zsh(tree)
    if shell == "fish":
        return gen_fish(tree)
    raise ValueError(f"unsupported shell: {shell}")
